# Deterministic high-resolution raster exports, not AI-generated bitmaps.
Add-Type -AssemblyName System.Drawing
function Drawing-Path([string]$data) {
    $drawing = [Drawing.Drawing2D.GraphicsPath]::new()
    [single]$x = 0; [single]$y = 0
    foreach ($command in @(Read-Commands $data)) {
        $v = @($command.Values | ForEach-Object { [single](Number $_) })
        switch ($command.Kind) {
            'M' { $drawing.StartFigure(); $x = $v[0]; $y = $v[1] }
            'L' { $drawing.AddLine($x, $y, $v[0], $v[1]); $x = $v[0]; $y = $v[1] }
            'Q' {
                $drawing.AddBezier($x, $y, ($x + 2 * ($v[0] - $x) / 3), ($y + 2 * ($v[1] - $y) / 3), ($v[2] + 2 * ($v[0] - $v[2]) / 3), ($v[3] + 2 * ($v[1] - $v[3]) / 3), $v[2], $v[3])
                $x = $v[2]; $y = $v[3]
            }
            'C' { $drawing.AddBezier($x, $y, $v[0], $v[1], $v[2], $v[3], $v[4], $v[5]); $x = $v[4]; $y = $v[5] }
            'Z' { $drawing.CloseFigure() }
        }
    }
    return ,$drawing
}

function Raster-Bytes([int]$edge) {
    $large = $edge * 4
    $bitmap = [Drawing.Bitmap]::new($large, $large)
    $graphics = [Drawing.Graphics]::FromImage($bitmap)
    try {
        $graphics.SmoothingMode = [Drawing.Drawing2D.SmoothingMode]::AntiAlias
        $graphics.ScaleTransform(($large / 108), ($large / 108))
        $background = [Drawing.Drawing2D.GraphicsPath]::new()
        $radius = [single](Number $svg.svg.rect.rx)
        $diameter = 2 * $radius
        $background.AddArc(0, 0, $diameter, $diameter, 180, 90)
        $background.AddArc((108 - $diameter), 0, $diameter, $diameter, 270, 90)
        $background.AddArc((108 - $diameter), (108 - $diameter), $diameter, $diameter, 0, 90)
        $background.AddArc(0, (108 - $diameter), $diameter, $diameter, 90, 90)
        $background.CloseFigure()
        $brush = [Drawing.SolidBrush]::new([Drawing.ColorTranslator]::FromHtml($svg.svg.rect.fill))
        $graphics.FillPath($brush, $background)
        $brush.Dispose(); $background.Dispose()
        $pen = [Drawing.Pen]::new([Drawing.ColorTranslator]::FromHtml($group.stroke), [single]$strokeWidth)
        $pen.StartCap = [Drawing.Drawing2D.LineCap]::Round
        $pen.EndCap = [Drawing.Drawing2D.LineCap]::Round
        $pen.LineJoin = [Drawing.Drawing2D.LineJoin]::Round
        foreach ($path in $paths) { $shape = Drawing-Path $path.d; $graphics.DrawPath($pen, $shape); $shape.Dispose() }
        $pen.Dispose()
        $small = [Drawing.Bitmap]::new($edge, $edge)
        $resample = [Drawing.Graphics]::FromImage($small)
        try {
            $resample.InterpolationMode = [Drawing.Drawing2D.InterpolationMode]::HighQualityBicubic
            $resample.PixelOffsetMode = [Drawing.Drawing2D.PixelOffsetMode]::HighQuality
            $resample.DrawImage($bitmap, 0, 0, $edge, $edge)
            $stream = [IO.MemoryStream]::new()
            try { $small.Save($stream, [Drawing.Imaging.ImageFormat]::Png); return ,$stream.ToArray() }
            finally { $stream.Dispose() }
        } finally { $resample.Dispose(); $small.Dispose() }
    } finally { $graphics.Dispose(); $bitmap.Dispose() }
}

