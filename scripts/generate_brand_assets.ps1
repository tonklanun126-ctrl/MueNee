function Read-Commands([string]$data) {
    $tokens = [regex]::Matches($data, '[MLQCZ]|-?\d+(?:\.\d+)?')
    if (($tokens.Value -join '') -ne ($data -replace '[\s,]', '')) {
        throw 'Only absolute M/L/Q/C/Z SVG commands are supported.'
    }
    $arity = @{ M = 2; L = 2; Q = 4; C = 6; Z = 0 }
    $index = 0
    while ($index -lt $tokens.Count) {
        $kind = $tokens[$index++].Value
        if (-not $arity.ContainsKey($kind)) { throw 'Expected an explicit path command.' }
        $values = @()
        for ($argument = 0; $argument -lt $arity[$kind]; $argument++) {
            if ($index -ge $tokens.Count) { throw 'Incomplete SVG path command.' }
            $values += $tokens[$index++].Value
        }
        [PSCustomObject]@{ Kind = $kind; Values = $values }
    }
}

function Generated-Text([string]$relative, [string]$content) {
    $target = Join-Path $brandProject $relative
    if ($Check) {
        if (-not (Test-Path -LiteralPath $target) -or [IO.File]::ReadAllText($target) -ne $content) {
            throw "Generated asset is stale: $relative"
        }
    } else {
        [IO.Directory]::CreateDirectory([IO.Path]::GetDirectoryName($target)) | Out-Null
        [IO.File]::WriteAllText($target, $content, $utf8)
    }
}

